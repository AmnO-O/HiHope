def now_iso() -> str:
    return datetime.now(timezone.utc).isoformat(timespec='seconds')


def load_candidates() -> List[Dict[str, Any]]:
    candidates: List[Dict[str, Any]] = []

    # Priority 1: Load from JSON metadata
    if os.path.exists(ARGS.input_json) and not ARGS.input_tsv:
        try:
            with open(ARGS.input_json, 'r', encoding='utf-8') as f:
                data = json.load(f)
            items = data.get('items', [])
            for it in items:
                source_id = it.get('source_id') or it.get('id', '')
                src_meta = it.get('source', {})
                orig_ctx = it.get('original') or src_meta.get('context', '')
                compound = it.get('compound') or src_meta.get('compound', '')
                lang = it.get('lang', 'en')
                kind = it.get('kind', 'nn')
                variants = it.get('variants', [])
                if not variants and it.get('rewritten'):
                    variants = [it['rewritten']]

                for v_idx, v_text in enumerate(variants, start=1):
                    cand_id = f"XSYNTH{source_id}V{v_idx}"
                    candidates.append({
                        'cand_id': cand_id,
                        'source_id': source_id,
                        'variant_idx': v_idx,
                        'lang': lang,
                        'kind': kind,
                        'compound': compound,
                        'mod': src_meta.get('mod', ''),
                        'head': src_meta.get('head', ''),
                        'mod_avg': src_meta.get('mod_avg'),
                        'mod_std': src_meta.get('mod_std'),
                        'head_avg': src_meta.get('head_avg'),
                        'head_std': src_meta.get('head_std'),
                        'source_context': orig_ctx,
                        'candidate_context': v_text.strip(),
                    })
            print(f"Loaded {len(candidates)} candidates from JSON registry: {ARGS.input_json}")
            return candidates
        except Exception as e:
            print(f"[Warning] Failed to load JSON registry {ARGS.input_json}: {e}")

    # Priority 2: Load from TSV files
    tsv_patterns = ARGS.input_tsv or ['gen/synth/*.tsv']
    tsv_files: List[str] = []
    for pat in tsv_patterns:
        tsv_files.extend(glob.glob(pat))

    for p in sorted(set(tsv_files)):
        m = re.search(r'(SynthNN|SynthPV)_(en|de)', p, re.IGNORECASE)
        kind = 'nn' if m and 'nn' in m.group(1).lower() else 'pv'
        lang = m.group(2).lower() if m else 'en'
        try:
            with open(p, 'r', encoding='utf-8', errors='replace', newline='') as f:
                reader = csv.reader(f, delimiter='\t')
                header = next(reader, None)
                if not header:
                    continue
                idx = {k: i for i, k in enumerate(header)}
                for row in reader:
                    if len(row) <= max(idx.values()):
                        continue
                    cid = row[idx['ContextID']].strip()
                    ctx = row[idx['Context']].strip()
                    comp = row[idx['Compound']].strip() if 'Compound' in idx else row[idx['ParticleVerb']].strip()
                    mod = row[idx['Mod']].strip() if 'Mod' in idx else row[idx['Base']].strip()
                    head = row[idx['Head']].strip() if 'Head' in idx else row[idx['Particle']].strip()

                    candidates.append({
                        'cand_id': cid,
                        'source_id': cid,
                        'variant_idx': 1,
                        'lang': lang,
                        'kind': kind,
                        'compound': comp,
                        'mod': mod,
                        'head': head,
                        'mod_avg': float(row[idx['ModAvg']]) if 'ModAvg' in idx else float(row[idx['Avg']]),
                        'mod_std': float(row[idx['ModStd']]) if 'ModStd' in idx else float(row[idx['Std']]),
                        'head_avg': float(row[idx['HeadAvg']]) if 'HeadAvg' in idx else float(row[idx['Avg']]),
                        'head_std': float(row[idx['HeadStd']]) if 'HeadStd' in idx else float(row[idx['Std']]),
                        'source_context': f"Target '{comp}' used in context.",
                        'candidate_context': ctx,
                    })
        except Exception as e:
            print(f"[Error reading {p}]: {e}")

    print(f"Loaded {len(candidates)} candidates from {len(tsv_files)} TSV files.")
    return candidates


