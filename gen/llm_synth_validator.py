def get_checkpoint_jsonl_path(out_path: str) -> str:
    base, _ = os.path.splitext(out_path)
    return f"{base}.checkpoint.jsonl"


def append_checkpoint_jsonl(out_path: str, record: Dict[str, Any]):
    jsonl_path = get_checkpoint_jsonl_path(out_path)
    os.makedirs(os.path.dirname(os.path.abspath(jsonl_path)) or '.', exist_ok=True)
    with open(jsonl_path, 'a', encoding='utf-8') as f:
        f.write(json.dumps(record, ensure_ascii=False) + '\n')


def load_existing_reviews(out_path: str) -> Dict[str, Dict[str, Any]]:
    if ARGS.fresh:
        jsonl_path = get_checkpoint_jsonl_path(out_path)
        if os.path.exists(jsonl_path):
            try:
                os.remove(jsonl_path)
            except Exception:
                pass
        return {}

    reviews_map: Dict[str, Dict[str, Any]] = {}

    # 1. Main JSON report
    if os.path.exists(out_path):
        try:
            with open(out_path, 'r', encoding='utf-8') as f:
                data = json.load(f)
            for r in data.get('reviews', []):
                r_id = r.get('id')
                if r_id:
                    reviews_map[r_id] = r
        except Exception as e:
            print(f"  [Warning] Could not load report from {out_path}: {e}")

    # 2. Incremental JSONL
    jsonl_path = get_checkpoint_jsonl_path(out_path)
    if os.path.exists(jsonl_path):
        try:
            with open(jsonl_path, 'r', encoding='utf-8', errors='replace') as f:
                for line in f:
                    line = line.strip()
                    if not line:
                        continue
                    try:
                        rec = json.loads(line)
                        r_id = rec.get('id')
                        if r_id:
                            reviews_map[r_id] = rec
                    except Exception:
                        pass
        except Exception as e:
            print(f"  [Warning] Could not read JSONL checkpoint {jsonl_path}: {e}")

    if reviews_map:
        print(f"  [Checkpoint Loaded] Found {len(reviews_map)} previously evaluated candidates.")
    return reviews_map


def atomic_save_json(path: str, data: Any):
    dir_name = os.path.dirname(os.path.abspath(path)) or '.'
    os.makedirs(dir_name, exist_ok=True)
    fd, tmp_path = tempfile.mkstemp(dir=dir_name, suffix='.tmp')
    try:
        with os.fdopen(fd, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
        os.replace(tmp_path, path)
    finally:
        if os.path.exists(tmp_path):
            os.remove(tmp_path)


def write_verified_tsv(verified_items: List[Dict[str, Any]], tsv_dir: str):
    os.makedirs(tsv_dir, exist_ok=True)
    by_key: Dict[Tuple[str, str], List[Dict[str, Any]]] = {}
    for it in verified_items:
        by_key.setdefault((it['lang'], it['kind']), []).append(it)

    for (lang, kind), items in by_key.items():
        prefix = 'Verified_SynthNN' if kind == 'nn' else 'Verified_SynthPV'
        out_tsv = os.path.join(tsv_dir, f"{prefix}_{lang}.tsv")
        header = HEADER_NN if kind == 'nn' else HEADER_PV
        with open(out_tsv, 'w', encoding='utf-8', newline='') as f:
            f.write('\t'.join(header) + '\n')
            for c in sorted(items, key=lambda x: x['cand_id']):
                ctx_clean = re.sub(r'[\t\r\n]+', ' ', c['candidate_context']).strip()
                if kind == 'nn':
                    row = [
                        c['cand_id'], c['compound'], c['mod'], c['head'],
                        f"{c['mod_avg']:.6f}" if c['mod_avg'] is not None else '',
                        f"{c['mod_std']:.6f}" if c['mod_std'] is not None else '',
                        f"{c['head_avg']:.6f}" if c['head_avg'] is not None else '',
                        f"{c['head_std']:.6f}" if c['head_std'] is not None else '',
                        ctx_clean,
                    ]
                else:
                    row = [
                        c['cand_id'], c['compound'], c['mod'], c['head'],
                        f"{c['mod_avg']:.6f}" if c['mod_avg'] is not None else '',
                        f"{c['mod_std']:.6f}" if c['mod_std'] is not None else '',
                        ctx_clean,
                    ]
                f.write('\t'.join(row) + '\n')
        print(f"  Exported {len(items)} verified rows to: {out_tsv}")


def main():
    print("=" * 64)
    print(" LLM-as-a-Judge Batch QA Validator for Synthetic Data")
    print("=" * 64)

    candidates = load_candidates()
    if not candidates:
        sys.exit("No candidates found to validate.")

    if ARGS.limit:
        candidates = candidates[:ARGS.limit]

    if ARGS.dry_run:
        print(f"[DRY RUN] Found {len(candidates)} candidate sentences across all datasets.")
        est_batches = (len(candidates) + ARGS.batch_size - 1) // ARGS.batch_size
        print(f"Estimated Judge API calls: {est_batches} (at batch-size={ARGS.batch_size})")
        return

    # Auto-load existing checkpoint
    existing_reviews = load_existing_reviews(ARGS.out_report)
    done_ids: Set[str] = set(existing_reviews.keys())

    todo_candidates = [c for c in candidates if c['cand_id'] not in done_ids]
    print(f"Candidates to review: {len(todo_candidates)} / {len(candidates)}")

    if not todo_candidates:
        print("All candidates have already been reviewed!")
        cand_lookup = {c['cand_id']: c for c in candidates}
        verified_items = [cand_lookup[r_id] for r_id, r in existing_reviews.items() if r.get('decision') == 'PASS' and r_id in cand_lookup]
        write_verified_tsv(verified_items, ARGS.tsv_dir)
        return

    client_tuple = init_judge_client()
    concurrency = ARGS.max_concurrency or (6 if client_tuple[0] == 'gemini' else 4)
    print(f"Judge API: {client_tuple[0]} | Model: {client_tuple[2]} | Concurrency: {concurrency}")

    batches = [todo_candidates[i:i + ARGS.batch_size] for i in range(0, len(todo_candidates), ARGS.batch_size)]
    print(f"Total API Batches to review: {len(batches)} (Batch size: {ARGS.batch_size})")

    reviews_all_dict: Dict[str, Dict[str, Any]] = dict(existing_reviews)
    cand_lookup = {c['cand_id']: c for c in candidates}

    def persist_validator_snapshot():
        reviews_list = sorted(reviews_all_dict.values(), key=lambda x: x['id'])
        passed_cands = [cand_lookup[r['id']] for r in reviews_list if r.get('decision') == 'PASS' and r['id'] in cand_lookup]
        pass_rate = (len(passed_cands) / max(1, len(reviews_list))) * 100
        meta = {
            'generator': 'llm_synth_validator.py',
            'judge_api': client_tuple[0],
            'judge_model': client_tuple[2],
            'total_reviewed': len(reviews_list),
            'total_passed': len(passed_cands),
            'pass_rate': f"{pass_rate:.1f}%",
            'updated_at': now_iso(),
            'reviews': reviews_list,
        }
        atomic_save_json(ARGS.out_report, meta)
        write_verified_tsv(passed_cands, ARGS.tsv_dir)
        return len(passed_cands), pass_rate

    def process_review_batch(batch: List[Dict[str, Any]]) -> Dict[str, Dict[str, str]]:
        system, user = build_judge_prompt(batch)
        for attempt in range(1, ARGS.max_retries + 1):
            try:
                raw_out = call_judge_api(client_tuple, system, user)
                return parse_judge_response(raw_out, batch)
            except RetryableAPIError:
                if attempt >= ARGS.max_retries:
                    break
                time.sleep(2.0 * attempt + random.uniform(0.1, 0.5))
            except Exception as e:
                if attempt >= ARGS.max_retries:
                    print(f"  [Batch Failed]: {e}", file=sys.stderr)
                    break
                time.sleep(2.0 * attempt)
        return {c['cand_id']: {'decision': 'FAIL', 'reason': 'Max API retries exceeded'} for c in batch}

    t0 = time.time()
    processed_count = 0

    try:
        with ThreadPoolExecutor(max_workers=concurrency) as executor:
            for i in range(0, len(batches), concurrency):
                chunk = batches[i:i + concurrency]
                future_map = {executor.submit(process_review_batch, b): b for b in chunk}

                for future in as_completed(future_map):
                    b = future_map[future]
                    decisions = future.result()
                    processed_count += len(b)

                    for c in b:
                        cid = c['cand_id']
                        dec_info = decisions.get(cid, {'decision': 'FAIL', 'reason': 'Unknown'})
                        rec = {
                            'id': cid,
                            'compound': c['compound'],
                            'decision': dec_info['decision'],
                            'reason': dec_info['reason'],
                            'candidate_context': c['candidate_context'],
                            'source_context': c['source_context'],
                            'reviewed_at': now_iso(),
                        }
                        reviews_all_dict[cid] = rec
                        append_checkpoint_jsonl(ARGS.out_report, rec)

                # Persist snapshot after every chunk of batches
                passed_count, pass_rate = persist_validator_snapshot()
                elapsed = time.time() - t0
                speed = processed_count / max(elapsed, 0.001)
                print(f"  Progress: {processed_count}/{len(todo_candidates)} reviewed ({speed:.1f} items/s) | "
                      f"Passed: {passed_count} ({pass_rate:.1f}%)",
                      flush=True)

                if ARGS.delay > 0:
                    time.sleep(ARGS.delay)

    except KeyboardInterrupt:
        print("\n[Ctrl+C] Stopping cleanly and saving progress...")
    finally:
        passed_count, pass_rate = persist_validator_snapshot()
        print("\n" + "=" * 64)
        print(" Validation Complete!")
        print(f" Total Reviewed: {len(reviews_all_dict)}")
        print(f" Verified & Passed: {passed_count} ({pass_rate:.1f}%)")
        print(f" Validation Report: {ARGS.out_report}")
        print(f" Verified TSVs saved to: {ARGS.tsv_dir}/Verified_Synth*.tsv")
        print("=" * 64)


if __name__ == '__main__':
    main()
