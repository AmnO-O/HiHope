"""
LLM-as-a-Judge Batch Validator for Synthetic Compositionality Paraphrases.

Reviews synthetic sentences generated by ``llm_synth_comp_augment.py`` using an
independent LLM judge to guarantee that:
  1. Sense Consistency (Critical): The target construction preserves the EXACT same
     idiomatic / non-compositional reading as the gold source sentence.
  2. Syntactic Integrity: The target words appear in natural, grammatical positions.
  3. Fluency & Cleanliness: Free of AI artifacts, hallucinations, or garbled syntax.

Evaluates candidates in BATCHES (e.g. 10–20 pairs per API call) to cut latency & cost.

Outputs:
  - {out_dir}/validation_report.json            : Detailed audit log with pass/fail reasons
  - {tsv_dir}/Verified_SynthNN_{en|de}.tsv      : Filtered high-confidence NN training rows
  - {tsv_dir}/Verified_SynthPV_{en|de}.tsv      : Filtered high-confidence PV training rows

Usage:
  # 1. Batch Review using Gemini (10 items per API call):
  python gen/llm_synth_validator.py --api gemini --batch-size 10

  # 2. Cross-Model Review using Groq (e.g. Llama-3.3-70b or GPT-OSS-120B as Judge):
  python gen/llm_synth_validator.py --api groq --model llama-3.3-70b-versatile --batch-size 10

  # 3. Dry run to inspect candidates without making API calls:
  python gen/llm_synth_validator.py --dry-run

  # 4. Resume interrupted validation:
  python gen/llm_synth_validator.py --resume
"""

