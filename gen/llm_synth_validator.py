def init_judge_client() -> Tuple[str, Any, str]:
    if ARGS.api == 'gemini':
        try:
            from google import genai
            key = os.environ.get('GEMINI_API_KEY')
            if not key:
                raise SystemExit('Missing GEMINI_API_KEY in environment or .env')
            model = ARGS.model or 'gemini-3.5-flash-lite'
            return ('gemini', genai.Client(api_key=key), model)
        except ImportError:
            raise SystemExit('Please install google-genai: pip install google-genai')

    elif ARGS.api == 'groq':
        try:
            from openai import OpenAI
            key = os.environ.get('GROQ_API_KEY')
            if not key:
                raise SystemExit('Missing GROQ_API_KEY in environment or .env')
            model = ARGS.model or 'llama-3.3-70b-versatile'
            return ('groq', OpenAI(api_key=key, base_url='https://api.groq.com/openai/v1'), model)
        except ImportError:
            raise SystemExit('Please install openai: pip install openai')

    raise ValueError(f"Unknown API provider: {ARGS.api}")


def build_judge_prompt(batch: List[Dict[str, Any]]) -> Tuple[str, str]:
    system = JUDGE_BATCH_SYSTEM_PROMPT.format(batch_size=len(batch))
    items_payload = [
        {
            "id": c['cand_id'],
            "construction": c['compound'],
            "gold_source_sentence": c['source_context'],
            "candidate_sentence": c['candidate_context'],
            "language": c['lang'].upper(),
        }
        for c in batch
    ]
    user = (
        f"Review this batch of {len(batch)} candidate paraphrases for compositionality sense preservation:\n"
        f"{json.dumps(items_payload, ensure_ascii=False, indent=2)}\n\n"
        f"Provide your QA decision (PASS or FAIL) and reason for each item in the specified JSON format:"
    )
    return system, user


def call_judge_api(client_tuple: Tuple[str, Any, str], system_prompt: str, user_prompt: str) -> str:
    kind, cli, model_name = client_tuple
    if kind == 'gemini':
        from google.genai import types
        from google.genai import errors as genai_errors
        try:
            config = types.GenerateContentConfig(
                system_instruction=system_prompt,
                temperature=0.1,  # Low temperature for deterministic judgment
                max_output_tokens=2048,
                response_mime_type="application/json",
            )
            resp = cli.models.generate_content(
                model=model_name,
                contents=user_prompt,
                config=config,
            )
            return resp.text or ""
        except genai_errors.APIError as e:
            if getattr(e, 'code', None) in (429, 500, 502, 503, 504):
                raise RetryableAPIError() from e
            raise FatalAPIError(f"Gemini API Error: {e}") from e
    elif kind == 'groq':
        from openai import APIStatusError, RateLimitError
        try:
            resp = cli.chat.completions.create(
                model=model_name,
                messages=[
                    {'role': 'system', 'content': system_prompt},
                    {'role': 'user', 'content': user_prompt},
                ],
                temperature=0.1,
                max_tokens=2048,
                response_format={"type": "json_object"},
            )
            return resp.choices[0].message.content or ""
        except (RateLimitError, APIStatusError) as e:
            raise RetryableAPIError() from e


def parse_judge_response(raw_text: str, batch: List[Dict[str, Any]]) -> Dict[str, Dict[str, str]]:
    cleaned = raw_text.strip()
    cleaned = re.sub(r'^```(?:json)?\s*', '', cleaned)
    cleaned = re.sub(r'\s*```$', '', cleaned).strip()

    decisions: Dict[str, Dict[str, str]] = {}
    row_ids = {c['cand_id'] for c in batch}

    try:
        data = json.loads(cleaned)
        reviews = data.get('reviews') or data.get('results') or data.get('items') or []
        if isinstance(reviews, list):
            for rev in reviews:
                if isinstance(rev, dict):
                    r_id = str(rev.get('id', '')).strip()
                    dec = str(rev.get('decision', '')).strip().upper()
                    reason = str(rev.get('reason', '')).strip()
                    if r_id in row_ids:
                        decisions[r_id] = {
                            'decision': 'PASS' if 'PASS' in dec else 'FAIL',
                            'reason': reason or ('Passed checks' if 'PASS' in dec else 'Failed sense consistency'),
                        }
    except Exception:
        pass

    # Default missing items to FAIL with parsing notice
    for c in batch:
        cid = c['cand_id']
        if cid not in decisions:
            decisions[cid] = {'decision': 'FAIL', 'reason': 'Judge response missing or unparseable'}
    return decisions


